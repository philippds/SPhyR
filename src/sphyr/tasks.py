"""Task construction for the SPhyR benchmark: dataset records in, prompts out.

This module holds everything needed to turn a SPhyR dataset record into the
prompt an agent is shown.  It is deliberately free of any model, provider or
scoring code so that the OpenEnv environment in ``sphyr_env`` can build its
observations from it.
"""

